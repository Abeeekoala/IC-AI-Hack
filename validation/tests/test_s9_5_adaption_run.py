import importlib.util
import json
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(ROOT / "src")]
spec = importlib.util.spec_from_file_location("s9_5_adaption_run", ROOT / "scripts" / "s9_5_adaption_run.py")
run = importlib.util.module_from_spec(spec)
spec.loader.exec_module(run)


def test_scrub_replaces_emails_and_user_folders_and_keeps_the_rest():
    text = "metadata = {'author': 'Jane Doe <jane.doe@lab.example.edu>'}\n# C:/Users/ferna/AppData/x.json and /Users/bob/code\nx = 1\n"
    new, n = run.scrub(text)
    assert "jane.doe@lab.example.edu" not in new and "redacted@example.com" in new
    assert "C:/Users/user/AppData/x.json" in new and "/Users/user/code" in new and "ferna" not in new and "bob" not in new
    assert n == 3 and new.endswith("x = 1\n") and "Jane Doe" in new  # names are not removed, only addresses and folders


def test_scrub_rows_keeps_code_that_parsed_parsing_and_counts_changed_rows():
    rows = [{"prompt": "p", "completion": "a = 'x@y.org'\n"}, {"prompt": "p2", "completion": "b = 2\n"}]
    out, changed, total = run.scrub_rows(rows)
    assert changed == 1 and total == 1 and out[1] == rows[1] and "x@y.org" not in out[0]["completion"]


def test_clearances_come_from_the_sources_files_and_a_missing_source_is_an_error(tmp_path):
    src = tmp_path / "s.json"
    src.write_text(json.dumps({"licences_cleared": ["MIT"], "sources": [
        {"repo": "a/b", "commit": "1234567890", "spdx": "MIT"}, {"repo": "c/d", "commit": "abcdef0123", "spdx": None}]}))
    man = {"included": [{"source": "a/b@1234567"}, {"source": "c/d@abcdef0"}, {"source": "vaxforge-synthetic"},
                        {"source": "Opentrons/Protocols@2f447c9"}]}
    out = run.clearances(man, [src])
    assert out["a/b@1234567"].startswith("MIT") and "owner's decision" in out["c/d@abcdef0"]
    assert "owner's decision" in out["Opentrons/Protocols@2f447c9"] and "generated by this project" in out["vaxforge-synthetic"]
    man["included"].append({"source": "x/y@0000000"})
    with pytest.raises(ValueError, match="x/y@0000000"):
        run.clearances(man, [src])


def test_the_run_stops_and_cancels_at_the_deadline(monkeypatch):
    calls = []
    monkeypatch.setattr(run.ad, "get_run", lambda rid: calls.append(rid) or {"status": "running", "iterations_completed": 0, "max_iterations": 2})
    monkeypatch.setattr(run.time, "sleep", lambda s: None)
    last, timed_out = run.watch("run_1", deadline=run.time.monotonic() - 1, poll=0)
    assert timed_out is True and last["status"] == "running" and calls == ["run_1"]
    monkeypatch.setattr(run.ad, "get_run", lambda rid: {"status": "succeeded"})
    last, timed_out = run.watch("run_1", deadline=run.time.monotonic() + 60, poll=0)
    assert timed_out is False and last["status"] == "succeeded"
