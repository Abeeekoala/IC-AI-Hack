#!/usr/bin/env python3
"""Run the S9.5 fine-tune on Adaption: upload the audited training file, start one capped run, watch it, cancel at the cap.

    python3 scripts/s9_5_adaption_run.py --manifest M.json --train T.jsonl --out DIR [--model Qwen/Qwen3.5-4B]
            [--max-iterations 2] [--target-win-rate 0.6] [--wall-clock-minutes 90] [--send]

Without --send nothing is sent: it prints the exact requests (key redacted) after every local check has passed. With
--send it needs ADAPTION_API_KEY in the environment (never printed) and spends the account's credits.

Local checks, in order, each failing closed: the manifest's rows are exactly the training file's rows; the guard
(vaxforge.s9_5_finetune.assert_run_allowed) passes: pinned model, row minimum, SFT only, every source cleared, no leakage
violation (validation/leakage_check.py is re-run here); the text to upload has personal strings replaced.

Time and cost control: the run is created with max_iterations and target_win_rate (the platform stops at whichever comes
first), the model is pinned, and this script polls every POLL_SECONDS and cancels the run at --wall-clock-minutes
(POST /cancel), then records what the platform reports. Progress is written to --out/state.json after each step, so a
second call with the same --out resumes (it never uploads or creates a second time).

Personal data: e-mail addresses and the user-folder part of file paths in other people's code are replaced by placeholders
in the uploaded text only (the manifest still holds the hashes of the original text, which the run record says).
Nothing else in the rows changes. Standard library plus the repository's own modules.
"""
import argparse
import ast
import hashlib
import json
import re
import sys
import time
import warnings
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from vaxforge import s9_5_adaption as ad  # noqa: E402
from vaxforge import s9_5_finetune as ft  # noqa: E402

POLL_SECONDS = 60
DEFAULT_MODEL = "Qwen/Qwen3.5-4B"
DATASET_NAME = "ot2-liquid-handling-sft"  # generic on purpose: this name is sent to the platform
KEY_PREFIX = "ot2-sft-"  # the idempotency key is sent too
OWNER_DECISION = ("no licence stated, or not one of the cleared licences; used on the project owner's decision for non-commercial "
                  "personal research (a decision, not a licence)")
SYNTHETIC_STATEMENT = "generated by this project (scripts/s9_5_synth.py); no third-party material"
EMAIL = re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+")
USER_DIR = re.compile(r"(?i)((?:[A-Z]:)?[\\/]+Users[\\/]+)[^\\/\s'\"]+")


def now():
    return datetime.now(timezone.utc).strftime("%H:%M:%SZ")


def say(text):
    print(f"[{now()}] {text}", flush=True)


# ---- local checks (pure) -------------------------------------------------------------------------------------------

def scrub(text):
    """-> (text with e-mail addresses and user-folder names replaced, number of replacements)."""
    n = 0

    def mail(_):
        nonlocal n
        n += 1
        return "redacted@example.com"

    def folder(m):
        nonlocal n
        n += 1
        return m.group(1) + "user"

    return USER_DIR.sub(folder, EMAIL.sub(mail, text)), n


def scrub_rows(rows):
    """-> (scrubbed rows, rows changed, replacements). A completion that parsed as Python must still parse."""
    out, changed, total = [], 0, 0
    for r in rows:
        new = {}
        for key in ("prompt", "completion"):
            new[key], k = scrub(r[key])
            total += k
        if new != r:
            changed += 1
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")  # other people's code: invalid escape sequences are not our concern
                try:
                    ast.parse(r["completion"])
                except SyntaxError:
                    pass
                else:
                    ast.parse(new["completion"])  # raises if the scrub broke code that used to parse
        out.append(new)
    return out, changed, total


def clearances(manifest, sources_files):
    """Source -> written clearance for every source in the manifest. A source with no record is an error, never a guess."""
    recorded = {}
    for path in sources_files:
        data = json.loads(Path(path).read_text(encoding="utf-8"))
        cleared = set(data.get("licences_cleared") or [])
        for s in data["sources"]:
            key = f"{s['repo']}@{s['commit'][:7]}"
            recorded[key] = f"{s['spdx']} (repository licence file)" if s.get("spdx") in cleared else OWNER_DECISION
    out, missing = {}, []
    for source in sorted({e["source"] for e in manifest["included"]}):
        if source == "vaxforge-synthetic":
            out[source] = SYNTHETIC_STATEMENT
        elif source.startswith("Opentrons/Protocols@"):
            out[source] = OWNER_DECISION  # the public library: no licence file, Opentrons states its copyright (README S9.5)
        elif source in recorded:
            out[source] = recorded[source]
        else:
            missing.append(source)
    if missing:
        raise ValueError(f"{len(missing)} source(s) have no record in the sources files: {', '.join(missing[:5])}")
    return out


def read_jsonl(path):
    return [json.loads(line) for line in Path(path).read_text(encoding="utf-8").splitlines() if line.strip()]


def write_jsonl(path, rows):
    Path(path).write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")


def sha256_file(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def load_state(path):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def save_state(path, state):
    path.write_text(json.dumps(state, indent=2, sort_keys=True) + "\n", encoding="utf-8")


# ---- the run ---------------------------------------------------------------------------------------------------------

def watch(run_id, deadline, *, poll=POLL_SECONDS):
    """Poll until the run is terminal or the deadline passes. -> (last run dict, timed_out)."""
    last = None
    while True:
        try:
            last = ad.get_run(run_id)
            say(f"run {last.get('status')}: iterations {last.get('iterations_completed')}/{last.get('max_iterations')}, "
                f"best_win_rate {last.get('best_win_rate')}")
            if last.get("status") in ad.RUN_DONE:
                return last, False
        except ad.AdaptionError as e:
            if e.status not in (502, 503, 504):
                raise
            say(f"HTTP {e.status} while polling (retrying)")
        except (ConnectionError, TimeoutError, OSError) as e:
            say(f"network error while polling ({type(e).__name__}); retrying")
        if time.monotonic() >= deadline:
            return last, True
        time.sleep(poll)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--manifest", required=True)
    ap.add_argument("--train", required=True, help="prompt/completion JSONL from `vaxforge finetune manifest --training-out`")
    ap.add_argument("--candidates", help="the candidate file the manifest was built from (for the leakage check)")
    ap.add_argument("--heldout-dir", help="Text2WetLab tasks directory for the leakage check")
    ap.add_argument("--sources", nargs="+", default=[str(ROOT / "validation" / "s9_5_corpus_sources.json"),
                                                     str(ROOT / "validation" / "s9_5_corpus_sources_extra.json")])
    ap.add_argument("--out", required=True)
    ap.add_argument("--model", default=DEFAULT_MODEL)
    ap.add_argument("--max-iterations", type=int, default=2)
    ap.add_argument("--target-win-rate", type=float, default=0.6)
    ap.add_argument("--wall-clock-minutes", type=float, default=90.0)
    ap.add_argument("--send", action="store_true", help="really upload and start the run (spends credits)")
    args = ap.parse_args(argv)

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    state_path = out / "state.json"
    state = load_state(state_path)

    manifest = json.loads(Path(args.manifest).read_text(encoding="utf-8"))
    rows = read_jsonl(args.train)
    n = manifest["counts"]["included"]
    if len(rows) != n:
        raise SystemExit(f"error: the training file has {len(rows)} rows but the manifest includes {n}")
    say(f"manifest: {n} rows ({manifest['counts']['included_synthetic']} synthetic), training file sha256 {sha256_file(args.train)[:16]}")

    scrubbed, changed, replaced = scrub_rows(rows)
    upload = out / "upload.jsonl"
    write_jsonl(upload, scrubbed)
    say(f"personal strings replaced in {changed} row(s) ({replaced} replacements); upload file {upload} sha256 {sha256_file(upload)[:16]}")

    cleared = clearances(manifest, args.sources)
    leak = []
    if args.candidates and args.heldout_dir:
        report = out / "leakage.txt"
        code = ft._validation_module("leakage_check").main([args.manifest, args.candidates, "--heldout-dir", args.heldout_dir, "--out", str(report)])
        leak = [] if code == 0 else [f"leakage_check exited {code}"]
        say(f"leakage check: {'0 violations' if code == 0 else 'FAILED (exit ' + str(code) + ')'}")
    else:
        leak = None  # "not run": the guard refuses
    guard = lambda: ft.assert_run_allowed(manifest, args.model, cleared, leak)  # noqa: E731
    guard()
    say("run guard: passes")

    slug = re.sub(r"[^a-z0-9]+", "-", args.model.lower()).strip("-")
    key = f"{KEY_PREFIX}{sha256_file(upload)[:12]}-{slug}-i{args.max_iterations}"  # one key per (data, model, iterations)
    if not args.send:
        say("DRY RUN: nothing is sent. The requests that --send would make:")
        print(json.dumps(ad.upload_training_file(upload, name=DATASET_NAME).to_dict(), indent=1))
        print(json.dumps(ad.create_run("DATASET_ID_FROM_UPLOAD", model=args.model, max_iterations=args.max_iterations,
                                       target_win_rate=args.target_win_rate, idempotency_key=key).to_dict(), indent=1))
        return 0

    started = time.monotonic()
    if "dataset_id" not in state:
        say("uploading the training file ...")
        made = ad.upload_training_file(upload, name=DATASET_NAME, confirm=True, guard=guard)
        state.update(dataset_id=made["dataset_id"], upload_sha256=made["file_sha256"], uploaded_at=now())
        save_state(state_path, state)
    say(f"dataset {state['dataset_id']} uploaded; waiting for it to be processed")
    status = ad.wait_for_dataset(state["dataset_id"])
    state["row_count"] = status.get("row_count")
    save_state(state_path, state)
    say(f"dataset processed: row_count {status.get('row_count')} (manifest {n})")
    if status.get("row_count") is not None and status["row_count"] < n:
        raise SystemExit(f"stop: the platform counts {status['row_count']} rows, fewer than the {n} uploaded; "
                         "that may put the run under its minimum. Nothing was started; decide before spending.")

    if "run_id" not in state:
        run = ad.create_run(state["dataset_id"], model=args.model, max_iterations=args.max_iterations,
                            target_win_rate=args.target_win_rate, idempotency_key=key, confirm=True, guard=guard)
        state.update(run_id=run["id"], run_created_at=now(), model=args.model, max_iterations=args.max_iterations,
                     target_win_rate=args.target_win_rate, wall_clock_minutes=args.wall_clock_minutes)
        save_state(state_path, state)
    say(f"run {state['run_id']} started (model {args.model}, max_iterations {args.max_iterations}, "
        f"target {args.target_win_rate}); cap {args.wall_clock_minutes:.0f} min")

    deadline = started + args.wall_clock_minutes * 60
    run, timed_out = watch(state["run_id"], deadline)
    if timed_out:
        say("wall-clock cap reached: cancelling the run")
        for attempt in range(5):
            try:
                ad.cancel_run(state["run_id"], confirm=True)
                break
            except ad.AdaptionError as e:
                say(f"cancel refused (HTTP {e.status}); retrying in 30 s")
                time.sleep(30)
        state["cancelled_at_cap"] = True
        run, _ = watch(state["run_id"], time.monotonic() + 300)
    state["final_status"] = run.get("status") if run else None
    save_state(state_path, state)

    if run:
        sha = None
        if run.get("download_available"):
            dest = out / f"checkpoint_{state['run_id']}.tar.gz"
            if not dest.exists():
                sha = ad.download_checkpoint(state["run_id"], dest)
                say(f"checkpoint downloaded: {dest} sha256 {sha[:16]}")
        launch = None
        try:
            launch = ad.get_best_launch_config(state["dataset_id"])
        except ad.AdaptionError as e:
            say(f"best launch config not available ({e})")
        path = ad.record_evidence(run, out, checkpoint_sha256=sha, launch_config=launch)
        say(f"evidence written: {path}")
    say(f"done: status {state['final_status']}, best_win_rate {run.get('best_win_rate') if run else None}")
    return 0 if state["final_status"] == "succeeded" else 3


if __name__ == "__main__":
    sys.exit(main())
